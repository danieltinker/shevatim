// Turns db/seed.json (a Catalog) into db/003_seed.sql: one call to shevatim.load_seed with the JSON embedded.
// Run: node db/seed.mjs   (re-run whenever seed.json changes, then commit 003_seed.sql)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function buildSeedSql(seedPath = join(here, "seed.json")) {
  const json = JSON.stringify(JSON.parse(readFileSync(seedPath, "utf8")));
  // a dollar-quote tag that cannot occur inside the JSON
  let tag = "seed_" + createHash("sha256").update(json).digest("hex").slice(0, 16);
  while (json.includes("$" + tag + "$")) tag += "x";
  return (
    "-- Generated by db/seed.mjs from db/seed.json. Do not edit by hand.\n" +
    "-- Safe to run again: only adds rows that are missing, never overwrites what the owner changed.\n" +
    `select shevatim.load_seed($${tag}$${json}$${tag}$::jsonb);\n`
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = join(here, "003_seed.sql");
  const sql = buildSeedSql();
  writeFileSync(out, sql);
  console.log(`wrote ${out} (${sql.length} bytes)`);
}
