// Touch check through the DevTools protocol: one finger on the cloth grabs it, a second finger pinches to zoom.
import { chromium } from "playwright";
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const types = { ".html": "text/html", ".js": "text/javascript", ".jpg": "image/jpeg" };
const server = http.createServer((req, res) => {
  const p = path.join(here, decodeURIComponent(req.url.split("?")[0]));
  fs.readFile(p, (err, data) => { if (err) { res.writeHead(404); res.end(); return; } res.writeHead(200, { "content-type": types[path.extname(p)] || "text/html" }); res.end(data); });
}).listen(0);
const exe = process.env.CHROME_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
const browser = await chromium.launch({ executablePath: exe, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 520 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
await page.goto(`http://localhost:${server.address().port}/index.html?live=1&quality=low&trim=tassels`);
await page.waitForFunction(() => window.ready || window.error, null, { timeout: 90000 });
const cdp = await ctx.newCDPSession(page);
const touch = (type, pts) => cdp.send("Input.dispatchTouchEvent", { type, touchPoints: pts.map(([x, y], id) => ({ x, y, id })) });
const view = () => page.evaluate(() => window.handle.lab.view());
const out = {};
await touch("touchStart", [[195, 290]]);
out.oneFingerGrabsCloth = (await view()).grabbed >= 0;
await touch("touchMove", [[230, 270]]); await page.waitForTimeout(100);
await touch("touchEnd", []);
out.releasedAfterLift = (await view()).grabbed === -1;
await touch("touchStart", [[30, 40]]);
await touch("touchMove", [[90, 44]]); await touch("touchMove", [[150, 46]]);
out.oneFingerOnEmptyOrbits = Math.abs((await view()).azimuth) > 0.2;
await touch("touchEnd", []);
await touch("touchStart", [[150, 60]]);
await touch("touchStart", [[150, 60], [240, 60]]);
await touch("touchMove", [[110, 60], [280, 60]]); await touch("touchMove", [[70, 60], [320, 60]]);
out.zoomAfterSpread = (await view()).zoom;
await touch("touchEnd", []);
console.log(JSON.stringify(out));
await browser.close(); server.close();
